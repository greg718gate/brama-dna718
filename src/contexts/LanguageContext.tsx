const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const STORAGE_KEY = "dna718_language";

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "pl" || saved === "en") return saved;

    // The Biblical Decoder app (also served inside Pi Browser) defaults to English.
    if (typeof window !== "undefined" && window.location.pathname.startsWith("/decoder")) {
      return "en";
    }

    const nav = (navigator.language || "").toLowerCase();
    return nav.startsWith("pl") ? "pl" : "en";
  });

  useEffect(() => {
    // Helps browsers (Brave/Chrome/etc.) offer proper auto-translation.
    document.documentElement.lang = language;
    localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const t = (key: string): string => {
    return translations[language]?.[key] ?? translations.pl[key] ?? key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};


export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider');
  }
  return context;
};
